//! Governance HTTP endpoints. Authentication is applied once by the parent router.

use crate::{
    modules::{
        alert, constraints, lifecycle, power_schedule, recommendation, rules, shared_env, tagging,
    },
    state::AppState,
};
use axum::{
    routing::{delete, get, patch, post, put},
    Router,
};

pub(super) fn router() -> Router<AppState> {
    Router::new()
        .route(
            "/api/v1/orgs/{org_id}/recommendations",
            get(recommendation::handlers::list),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/summary",
            get(recommendation::handlers::summary),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/checklist",
            get(recommendation::handlers::checklist_status),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/checklist",
            patch(recommendation::handlers::patch_checklist_modules),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/run",
            post(recommendation::handlers::trigger_run),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/{id}",
            get(recommendation::handlers::get),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/{id}/dismiss",
            post(recommendation::handlers::dismiss),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/{id}/reactivate",
            post(recommendation::handlers::reactivate),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/{id}/apply",
            post(recommendation::handlers::apply_recommendation),
        )
        .route(
            "/api/v1/orgs/{org_id}/recommendations/{id}/verify",
            post(recommendation::handlers::verify_recommendation),
        )
        .route(
            "/api/v1/orgs/{org_id}/alerts",
            get(alert::handlers::list_alerts),
        )
        .route(
            "/api/v1/orgs/{org_id}/alerts",
            post(alert::handlers::create_alert),
        )
        .route(
            "/api/v1/orgs/{org_id}/alerts/evaluate",
            post(alert::handlers::evaluate_alerts),
        )
        .route(
            "/api/v1/orgs/{org_id}/alerts/{id}",
            put(alert::handlers::update_alert).delete(alert::handlers::delete_alert),
        )
        .route(
            "/api/v1/orgs/{org_id}/events",
            get(alert::handlers::list_events),
        )
        .route(
            "/api/v1/orgs/{org_id}/alert-events",
            get(alert::handlers::list_alert_events),
        )
        .route(
            "/api/v1/orgs/{org_id}/assignment-rules",
            get(rules::handlers::list_rules),
        )
        .route(
            "/api/v1/orgs/{org_id}/assignment-rules",
            post(rules::handlers::create_rule),
        )
        .route(
            "/api/v1/orgs/{org_id}/assignment-rules/apply",
            post(rules::handlers::apply_rules),
        )
        .route(
            "/api/v1/orgs/{org_id}/assignment-rules/{id}",
            put(rules::handlers::update_rule),
        )
        .route(
            "/api/v1/orgs/{org_id}/assignment-rules/{id}",
            delete(rules::handlers::delete_rule),
        )
        .route(
            "/api/v1/orgs/{org_id}/constraints",
            get(constraints::handlers::list_constraints),
        )
        .route(
            "/api/v1/orgs/{org_id}/constraints",
            post(constraints::handlers::create_constraint),
        )
        .route(
            "/api/v1/orgs/{org_id}/constraints/evaluate",
            post(constraints::handlers::evaluate_constraints),
        )
        .route(
            "/api/v1/orgs/{org_id}/constraints/{id}",
            put(constraints::handlers::update_constraint),
        )
        .route(
            "/api/v1/orgs/{org_id}/constraints/{id}",
            delete(constraints::handlers::delete_constraint),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules",
            get(power_schedule::handlers::list_schedules),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules",
            post(power_schedule::handlers::create_schedule),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules/{id}",
            put(power_schedule::handlers::update_schedule),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules/{id}",
            delete(power_schedule::handlers::delete_schedule),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules/{id}/triggers",
            get(power_schedule::handlers::list_triggers),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules/{id}/triggers",
            post(power_schedule::handlers::create_trigger),
        )
        .route(
            "/api/v1/orgs/{org_id}/power-schedules/{id}/triggers/{trigger_id}",
            delete(power_schedule::handlers::delete_trigger),
        )
        .route(
            "/api/v1/orgs/{org_id}/tagging-policies",
            get(tagging::handlers::list_policies),
        )
        .route(
            "/api/v1/orgs/{org_id}/tagging-policies",
            post(tagging::handlers::create_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/tagging-policies/{id}",
            put(tagging::handlers::update_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/tagging-policies/{id}",
            delete(tagging::handlers::delete_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-tag",
            get(tagging::handlers::expenses_by_tag),
        )
        .route(
            "/api/v1/orgs/{org_id}/tagging/coverage",
            get(tagging::handlers::tag_coverage_analysis),
        )
        .route(
            "/api/v1/orgs/{org_id}/shared-environments",
            get(shared_env::handlers::list_environments)
                .post(shared_env::handlers::create_environment),
        )
        .route(
            "/api/v1/orgs/{org_id}/shared-environments/{id}",
            delete(shared_env::handlers::delete_environment),
        )
        .route(
            "/api/v1/orgs/{org_id}/shared-environments/{id}/book",
            post(shared_env::handlers::book_environment),
        )
        .route(
            "/api/v1/orgs/{org_id}/shared-environments/{id}/release",
            post(shared_env::handlers::release_environment),
        )
        .route(
            "/api/v1/orgs/{org_id}/shared-environments/{id}/bookings",
            get(shared_env::handlers::list_bookings),
        )
        .route(
            "/api/v1/orgs/{org_id}/lifecycle-policies",
            get(lifecycle::handlers::list_policies).post(lifecycle::handlers::create_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/lifecycle-policies/{id}",
            delete(lifecycle::handlers::delete_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/lifecycle-policies/{id}/evaluate",
            post(lifecycle::handlers::evaluate_policy),
        )
        .route(
            "/api/v1/orgs/{org_id}/lifecycle-events",
            get(lifecycle::handlers::list_events),
        )
}
