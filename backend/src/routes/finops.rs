//! Finops HTTP endpoints. Authentication is applied once by the parent router.

use crate::{
    modules::{bi_export, billing, expense},
    state::AppState,
};
use axum::{
    routing::{delete, get, patch, post, put},
    Router,
};

pub(super) fn router() -> Router<AppState> {
    Router::new()
        .route(
            "/api/v1/orgs/{org_id}/expenses",
            get(expense::handlers::list_expenses),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/summary",
            get(expense::handlers::summary),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-cloud",
            get(expense::handlers::by_cloud),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-pool",
            get(expense::handlers::by_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-region",
            get(expense::handlers::by_region),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-service",
            get(expense::handlers::by_service),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/trend",
            get(expense::handlers::trend),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/top-resources",
            get(expense::handlers::top_resources),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/forecast",
            get(expense::handlers::forecast_expenses),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/anomalies",
            get(expense::handlers::expense_anomalies),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/export",
            get(expense::handlers::export_expenses),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/heatmap",
            get(expense::handlers::expense_heatmap),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/by-tag-breakdown",
            get(expense::handlers::expenses_by_tag_breakdown),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/resources/{resource_id}/history",
            get(expense::handlers::resource_expense_history),
        )
        .route(
            "/api/v1/orgs/{org_id}/ri-coverage",
            get(expense::handlers::ri_coverage),
        )
        .route(
            "/api/v1/orgs/{org_id}/data-flow",
            get(expense::reporting::data_flow),
        )
        .route(
            "/api/v1/orgs/{org_id}/showback",
            get(expense::handlers::showback_report),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/cost-map",
            get(expense::handlers::cost_map),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/unit-economics",
            get(expense::handlers::unit_economics),
        )
        .route(
            "/api/v1/orgs/{org_id}/expenses/region-expenses",
            get(expense::handlers::region_expenses),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools",
            get(expense::pool_handlers::list_pools),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools",
            post(expense::pool_handlers::create_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/tree",
            get(expense::pool_handlers::get_pool_tree),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/budget-matrix",
            get(expense::pool_handlers::budget_matrix),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}",
            get(expense::pool_handlers::get_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}",
            put(expense::pool_handlers::update_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}",
            delete(expense::pool_handlers::delete_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}/trend",
            get(expense::pool_handlers::pool_expense_trend),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}/top-resources",
            get(expense::pool_handlers::pool_top_resources),
        )
        .route(
            "/api/v1/orgs/{org_id}/pools/{id}/parent",
            patch(expense::pool_handlers::move_pool),
        )
        .route(
            "/api/v1/orgs/{org_id}/cost-centers",
            get(expense::cost_center_handlers::list_cost_centers),
        )
        .route(
            "/api/v1/orgs/{org_id}/cost-centers",
            post(expense::cost_center_handlers::create_cost_center),
        )
        .route(
            "/api/v1/cost-centers/{id}",
            get(expense::cost_center_handlers::get_cost_center),
        )
        .route(
            "/api/v1/cost-centers/{id}",
            put(expense::cost_center_handlers::update_cost_center),
        )
        .route(
            "/api/v1/cost-centers/{id}",
            delete(expense::cost_center_handlers::delete_cost_center),
        )
        .route(
            "/api/v1/cost-centers/{id}/expenses",
            get(expense::cost_center_handlers::cost_center_expenses),
        )
        .route(
            "/api/v1/orgs/{org_id}/business-capabilities",
            get(expense::cost_center_handlers::list_business_capabilities)
                .post(expense::cost_center_handlers::create_business_capability),
        )
        .route(
            "/api/v1/business-capabilities/{id}",
            put(expense::cost_center_handlers::update_business_capability)
                .delete(expense::cost_center_handlers::delete_business_capability),
        )
        .route(
            "/api/v1/orgs/{org_id}/billing/import",
            post(billing::handlers::trigger_import),
        )
        .route(
            "/api/v1/orgs/{org_id}/billing/history",
            get(billing::handlers::list_import_history),
        )
        .route(
            "/api/v1/orgs/{org_id}/exchange-rates",
            get(billing::handlers::list_exchange_rates)
                .put(billing::handlers::upsert_exchange_rates),
        )
        .route(
            "/api/v1/orgs/{org_id}/bi-exports",
            get(bi_export::handlers::list_exports).post(bi_export::handlers::create_export),
        )
        .route(
            "/api/v1/orgs/{org_id}/bi-exports/{id}",
            put(bi_export::handlers::update_export).delete(bi_export::handlers::delete_export),
        )
        .route(
            "/api/v1/orgs/{org_id}/bi-exports/{id}/run",
            post(bi_export::handlers::run_export),
        )
        .route(
            "/api/v1/orgs/{org_id}/bi-exports/{id}/runs",
            get(bi_export::handlers::list_runs),
        )
        .route(
            "/api/v1/orgs/{org_id}/bi-exports/{id}/download",
            get(bi_export::handlers::download_run),
        )
}
